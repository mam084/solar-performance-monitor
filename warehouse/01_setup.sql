-- Solar Performance Monitor: Snowflake setup.
-- Three layers, one schema each:
--   RAW      readings exactly as they arrive (append-only, long format, no cleaning)
--   STAGING  one clean row per site per 15 minutes, canonical names and SI units
--   MARTS    what the app and analysts read: daily performance, events, tickets, decisions
--
-- The physics model and detector run in Python (solarmon.pipeline); they read STAGING
-- and write MARTS. Run these files in order as a role that can create databases.

CREATE DATABASE IF NOT EXISTS SOLARMON;
CREATE SCHEMA IF NOT EXISTS SOLARMON.RAW;
CREATE SCHEMA IF NOT EXISTS SOLARMON.STAGING;
CREATE SCHEMA IF NOT EXISTS SOLARMON.MARTS;

-- Small and auto-suspending: the daily run is a few minutes of work
CREATE WAREHOUSE IF NOT EXISTS SOLARMON_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- Roles: the pipeline writes, the app reads, reviewers write decisions only
CREATE ROLE IF NOT EXISTS SOLARMON_PIPELINE;
CREATE ROLE IF NOT EXISTS SOLARMON_APP;

GRANT USAGE ON WAREHOUSE SOLARMON_WH TO ROLE SOLARMON_PIPELINE;
GRANT USAGE ON WAREHOUSE SOLARMON_WH TO ROLE SOLARMON_APP;
GRANT USAGE ON DATABASE SOLARMON TO ROLE SOLARMON_PIPELINE;
GRANT USAGE ON DATABASE SOLARMON TO ROLE SOLARMON_APP;
GRANT ALL ON SCHEMA SOLARMON.RAW TO ROLE SOLARMON_PIPELINE;
GRANT ALL ON SCHEMA SOLARMON.STAGING TO ROLE SOLARMON_PIPELINE;
GRANT ALL ON SCHEMA SOLARMON.MARTS TO ROLE SOLARMON_PIPELINE;
GRANT USAGE ON SCHEMA SOLARMON.MARTS TO ROLE SOLARMON_APP;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SOLARMON.MARTS TO ROLE SOLARMON_APP;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SOLARMON.MARTS TO ROLE SOLARMON_APP;

-- Raw files land here (PVDAQ CSV/parquet today; a SCADA export in production)
CREATE STAGE IF NOT EXISTS SOLARMON.RAW.LANDING
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Raw site files, one folder per system_id';

CREATE FILE FORMAT IF NOT EXISTS SOLARMON.RAW.CSV_FMT
  TYPE = CSV PARSE_HEADER = TRUE FIELD_OPTIONALLY_ENCLOSED_BY = '"' NULL_IF = ('', 'NULL', 'NaN');

CREATE FILE FORMAT IF NOT EXISTS SOLARMON.RAW.PARQUET_FMT TYPE = PARQUET;
